// Vendor only the CPU simulation and its data structures from this project's reference.
// Acorn and eslint-scope resolve references lexically, including captures in nested functions.
const fs=require('node:fs'),path=require('node:path'),acorn=require('acorn'),scope=require('eslint-scope');
const root=path.join(__dirname,'..'), html=require('./branding.cjs').brand(fs.readFileSync(path.join(root,'Saltline.html'),'utf8'));
const js=html.match(/<script>([\s\S]*?)<\/script>/)[1];
const ast=acorn.parse(js,{ecmaVersion:2022,ranges:true});
const fn=ast.body[0].expression.callee,manager=scope.analyze(ast,{ecmaVersion:2022,sourceType:'script',optimistic:true,ignoreEval:true});
const outer=manager.acquire(fn),decls=[], extras=new Map();
for(const node of fn.body.body){
  if(node.type==='VariableDeclaration'){
    for(const d of node.declarations) if(d.id.type==='Identifier')decls.push({name:d.id.name,node:d,kind:node.kind});
  }else if(node.type==='FunctionDeclaration'||node.type==='ClassDeclaration')decls.push({name:node.id.name,node});
  else if(node.type==='ExpressionStatement'){
    const es=node.expression.type==='SequenceExpression'?node.expression.expressions:[node.expression];
    for(const e of es){if(e.type!=='AssignmentExpression')continue;let base=e.left;while(base.type==='MemberExpression')base=base.object;
      if(base.type!=='Identifier'||!outer.set.has(base.name))continue;
      const a=extras.get(base.name)||[];a.push(e);extras.set(base.name,a);}
  }
}
const refs=manager.scopes.flatMap(s=>s.references).filter(r=>r.resolved?.scope===outer).sort((a,b)=>a.identifier.start-b.identifier.start);
const all=new Map(decls.map(d=>[d.name,d])), selected=new Map();
function visitNode(node){
  let lo=0,hi=refs.length;while(lo<hi){const m=(lo+hi)>>1;if(refs[m].identifier.start<node.start)lo=m+1;else hi=m;}
  for(let i=lo;i<refs.length&&refs[i].identifier.start<node.end;i++)visit(refs[i].resolved.name);
}
function visit(name){if(selected.has(name))return;const d=all.get(name);if(!d)throw Error('No definition for '+name);
  selected.set(name,d);visitNode(d.node);for(const n of extras.get(name)||[])visitNode(n);
}
const names={Mesh:'Qe',Box:'un',Sphere:'ls',Matrix:'Ye',V3:'W',Camera:'Wn',Scene:'ir',Group:'wt',Color:'Ve',Material:'Qt',Unlit:'Nn',events:'Dy',rng:'il',physics:'d3',input:'v_',player:'x_',combat:'zv',weapon:'dm',enemies:'Em',audioGraph:'u_',silentAudio:'iC',hud:'hM',game:'mM',quality:'zy',settings:'Pi'};
Object.values(names).forEach(visit);
if(selected.has('gf')||selected.has('Hg')||selected.has('lt'))throw Error('A renderer or the whole namespace entered the CPU dependency graph');
const pieces=[];for(const d of selected.values()){
 pieces.push([d.node.start,(d.kind?d.kind+' ':'')+js.slice(d.node.start,d.node.end)+';']);
 for(const n of extras.get(d.name)||[])pieces.push([n.start,js.slice(n.start,n.end)+';']);
}
pieces.sort((a,b)=>a[0]-b[0]);
// Keep aim and HUD coordinates local when a host moves or resizes the component.
for(const part of pieces){
  if(part[1].startsWith('function hM('))part[1]=part[1].replace(/\binnerWidth\b/g,'environment.viewport().clientWidth').replace(/\binnerHeight\b/g,'environment.viewport().clientHeight');
  if(part[1].startsWith('function v_('))part[1]=part[1].replace('P.clientX/Math.max(1,innerWidth)','(P.clientX-environment.bounds().left)/Math.max(1,environment.bounds().width)').replace('P.clientY/Math.max(1,innerHeight)','(P.clientY-environment.bounds().top)/Math.max(1,environment.bounds().height)').replace('V.clientX<innerWidth*.45','V.clientX-environment.bounds().left<environment.bounds().width*.45');
}
const dir=path.join(root,'src/game/generated');fs.mkdirSync(dir,{recursive:true});
fs.writeFileSync(path.join(dir,'simulation.ts'),'// @ts-nocheck\n// Generated by tools/compile-game.cjs from the Saltline reference. CPU simulation only.\nexport function simulation(environment){\nconst {document,window,navigator,addEventListener,removeEventListener,matchMedia,setTimeout,clearTimeout,innerWidth,innerHeight,AudioContext,OfflineAudioContext}=environment;\n'+pieces.map(x=>x[1]).join('\n')+'\nreturn {'+Object.entries(names).map(([alias,name])=>alias+':'+name).join(',')+'};\n}\n');
const css=html.match(/<style>([\s\S]*?)<\/style>/)[1].replace(/:root/g,':host').replace(/html,\s*body/g,':host').replace(/\bbody\s*\{[^}]*\}/g,'').replace('#app { position: fixed;','#app { position: absolute;');
fs.writeFileSync(path.join(dir,'interface.ts'),'export const interfaceStyle='+JSON.stringify(css)+';\n');
console.log(selected.size+' CPU declarations, '+pieces.length+' fragments; no WebGL renderer.');
