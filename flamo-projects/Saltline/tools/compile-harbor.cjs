// Compile only the CPU geometry constructors and the registered harbour props from the reference.
const fs = require('node:fs');
const path = require('node:path');
const graph = require('./reference-graph.cjs');
const root = path.join(__dirname, '..');
const { readReference } = require('./branding.cjs');
function writeHarborWorker(dir) {
  const html = readReference();
  let js = html.match(/<script>([\s\S]*?)<\/script>/)[1];
  const bindings = {
    level: 'C1',
    backdrop: 'pv',
    props: 'Yg',
    rng: 'il',
    quality: 'zy',
    scene: 'ir',
    group: 'wt',
    mesh: 'Qe',
    geometry: 'nt',
    attribute: 'et',
    material: 'Qt',
    unlit: 'Nn',
    texture: 'xs',
    color: 'Ve',
    vector: 'W',
    normalMatrix: 'kt',
    physics: 'd3',
    events: 'Dy',
  };
  // Resolve named Three constructors before collecting dependencies.
  const namespace = js.match(/br\(lt,\{([^}]+)\}\)/)[1];
  const named = new Map(Array.from(namespace.matchAll(/(\w+):\(\)=>([\w$]+)/g), (m) => [m[1], m[2]]));
  js = js.replace(/\blt\.(\w+)/g, (match, key) => named.get(key) || match);
  js = js.replace('G:i,THREE:lt,staticRoot', 'G:i,staticRoot');
  const pieces = graph(js, bindings, '_i');
  const worker =
    'const window=self;const document={createElement:tag=>{if(tag==="canvas")return new OffscreenCanvas(1,1);throw Error(tag)}};\n' +
    pieces.map((p) => p[1]).join('\n') +
    '\nconst api={' +
    Object.entries(bindings)
      .map(([k, v]) => k + ':' + v)
      .join(',') +
    '};\n' +
    fs.readFileSync(path.join(__dirname, 'harbor-worker.js'), 'utf8');

  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(
    path.join(dir, 'worker.ts'),
    '// Generated by tools/compile-harbor.cjs\nexport default ' + JSON.stringify(worker) + ';\n',
  );
}
module.exports = { writeHarborWorker };
if (require.main === module)
  writeHarborWorker(path.resolve(process.argv[2] || path.join(root, 'src/harbor/baked')));
